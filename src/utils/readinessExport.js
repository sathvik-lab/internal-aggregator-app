/**
 * Readiness Export Utilities
 *
 * Generates plaintext and HTML summaries of inspection readiness status.
 *
 * ⚠️  SECURITY & PII CONSIDERATIONS:
 * - Data shared via Share API includes personal business information (business name, location, profile).
 * - Document details (permit/license numbers, expiry dates) are included.
 * - Recipient device/email is not under app control; assume data persists indefinitely.
 * - Do NOT include: user email, phone, internal user IDs, Firestore paths, or debug info.
 * - Share should be user-initiated only (button tap, not automatic).
 * - Consider adding a confirmation dialog warning user about data being shared.
 * - Future: add option to redact sensitive document details before sharing.
 */

/**
 * Generate plaintext readiness summary for sharing/export
 * @param {Object} dashboardData - Dashboard snapshot data
 * @param {Object} scoreData - Compliance score breakdown
 * @param {Object} businessProfile - Business profile (optional, for context)
 * @returns {string} Plaintext summary
 */
export const generateReadinessPlaintext = (dashboardData, scoreData, businessProfile = {}) => {
  if (!dashboardData || !scoreData) {
    return 'Readiness summary unavailable.';
  }

  const timestamp = new Date().toLocaleString();
  const { business_name = 'Food Truck', state = 'Unknown' } = businessProfile;

  const lines = [
    `INSPECTION READINESS SUMMARY`,
    `Generated: ${timestamp}`,
    `Business: ${business_name} (${state})`,
    ``,
    `━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━`,
    `READINESS SCORE: ${scoreData.score}% - ${scoreData.factors ? (scoreData.score >= 80 ? 'EXCELLENT' : scoreData.score >= 60 ? 'GOOD' : scoreData.score >= 40 ? 'FAIR' : 'LOW') : 'UNKNOWN'}`,
    `━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━`,
    ``,
    `COMPLIANCE BREAKDOWN:`,
    `• Checklist Completion: ${scoreData.checklistCompletion}%`,
    `  (${scoreData.factors?.completedChecklistItems || 0}/${scoreData.factors?.totalChecklistItems || 0} items)`,
    `• Overdue Items: ${scoreData.factors?.overdueCount || 0}`,
    `• Expiring Documents (30 days): ${scoreData.factors?.expiringCount || 0}`,
    `• Expired Documents: ${Math.max(0, (scoreData.factors?.expiredCount || 0))}`,
    `• Recent Evidence: ${scoreData.factors?.recentMediaLogsCount || 0} logs (last 7 days)`,
    ``,
  ];

  if (dashboardData.overdueItems && dashboardData.overdueItems.length > 0) {
    lines.push(`CRITICAL: ${dashboardData.overdueItems.length} OVERDUE ITEM(S)`);
    dashboardData.overdueItems.slice(0, 5).forEach((item) => {
      lines.push(`  - ${item.name || 'Unnamed item'}`);
    });
    if (dashboardData.overdueItems.length > 5) {
      lines.push(`  ... and ${dashboardData.overdueItems.length - 5} more`);
    }
    lines.push(``);
  }

  if (dashboardData.expiredDocuments && dashboardData.expiredDocuments.length > 0) {
    lines.push(`CRITICAL: ${dashboardData.expiredDocuments.length} EXPIRED DOCUMENT(S)`);
    dashboardData.expiredDocuments.slice(0, 5).forEach((doc) => {
      lines.push(`  - ${doc.documentType || 'Document'}: ${doc.expiryDate || 'date unknown'}`);
    });
    if (dashboardData.expiredDocuments.length > 5) {
      lines.push(`  ... and ${dashboardData.expiredDocuments.length - 5} more`);
    }
    lines.push(``);
  }

  if (dashboardData.expiringDocuments && dashboardData.expiringDocuments.length > 0) {
    lines.push(`WARNING: ${dashboardData.expiringDocuments.length} DOCUMENT(S) EXPIRING SOON`);
    dashboardData.expiringDocuments.slice(0, 5).forEach((doc) => {
      lines.push(`  - ${doc.documentType || 'Document'}: Expires ${doc.expiryDate || 'date unknown'}`);
    });
    if (dashboardData.expiringDocuments.length > 5) {
      lines.push(`  ... and ${dashboardData.expiringDocuments.length - 5} more`);
    }
    lines.push(``);
  }

  lines.push(
    ``,
    `DISCLAIMER:`,
    `This readiness summary is not a legal compliance guarantee. It is a`,
    `snapshot of your documented compliance status only. Please consult`,
    `with local health and safety authorities for definitive compliance`,
    `requirements. This app does not constitute legal advice.`,
    ``,
    `Generated by: Food Truck Compliance App`,
  );

  return lines.join('\n');
};

