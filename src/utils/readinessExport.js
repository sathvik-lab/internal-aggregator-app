/**
 * Share readiness summary via native share API
 * Supports plaintext and HTML formats
 *
 * ⚠️  SECURITY NOTE:
 * - Share API sends data to user-selected recipient (email, message, etc.).
 * - Data is not encrypted in transit through user's device apps.
 * - Recipients can forward, screenshot, or print the summary.
 * - Do not share user email, internal IDs, or debug paths.
 * - Always confirm user intent before sharing (button tap, not auto).
 *
 * @param {Object} dashboardData - Dashboard snapshot data
 * @param {Object} scoreData - Compliance score breakdown
 * @param {Object} businessProfile - Business profile
 * @returns {Promise<void>}
 */
export const shareReadinessSummary = async (dashboardData, scoreData, businessProfile = {}) => {
  const { Share } = await import('react-native');

  const plaintext = generateReadinessPlaintext(dashboardData, scoreData, businessProfile);
  const { business_name = 'Food Truck' } = businessProfile;

  try {
    await Share.share({
      message: plaintext,
      title: `${business_name} Readiness Summary`,
      url: undefined, // RN iOS may require this for HTML; we use message instead for text
    });
  } catch (error) {
    console.error('Share failed:', error);
    throw error;
  }
};
